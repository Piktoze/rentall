import assert from 'node:assert/strict';
import fs from 'node:fs';
const src=fs.readFileSync('./server.js','utf8');
const start=src.indexOf('async function cancelBookingWithPaymentHandling(');
const end=src.indexOf('\nfunction bookingAccessAllowed(',start);
assert.ok(start>=0&&end>start,'Booking cancellation path missing');
const route=src.slice(start,end);
const check=route.indexOf("if(!collectedPayment && booking.stripePaymentIntentId");
const retrieve=route.indexOf('await retrieveDirectChargePaymentIntent(stripe',check);
const succeeded=route.indexOf("if(stripeIntent.status==='succeeded')",retrieve);
const binding=route.indexOf("stripeIntent.metadata?.bookingId",succeeded);
const amount=route.indexOf('Number(stripeIntent.amount)',binding);
const currency=route.indexOf('stripeIntent.currency',amount);
const collected=route.indexOf('collectedPayment=true;',currency);
const compute=route.indexOf('const refundAmount=collectedPayment',collected);
const provider=route.indexOf('await handleStripeCancellationForBooking(booking,refundAmount)',compute);
const cancel=route.indexOf('cancelRentalBookingWithRefund(bookingId',provider);
assert.ok(check>=0&&retrieve>check&&succeeded>retrieve,'Must retrieve actual Stripe status when the webhook lags');
assert.ok(binding>succeeded&&amount>binding&&currency>amount&&collected>currency,'Succeeded charge must be verified as belonging to booking');
assert.ok(compute>collected&&provider>compute&&cancel>provider,'Stripe state must be reconciled before calculating refund and mutating cancellation');
assert.ok(route.includes("throw new Error('Cannot verify Stripe payment before cancellation')"),'Unknown payment state must fail closed');
console.log('PASS cancellation verifies delayed Stripe succeeded charge before refund computation');
