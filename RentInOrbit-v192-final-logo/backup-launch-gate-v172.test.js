import fs from 'node:fs';
const ok=(v,m)=>{if(!v)throw new Error(m)};
const server=fs.readFileSync('./server.js','utf8');
const backup=fs.readFileSync('./ops/backup-db.js','utf8');
const verify=fs.readFileSync('./ops/verify-backup.js','utf8');
const auto=fs.readFileSync('./ops/backup-and-verify.js','utf8');
const pkg=JSON.parse(fs.readFileSync('./package.json','utf8'));
ok(server.includes("database_backup_enabled")&&server.includes("database_backup_recent_verified"),'launch backup blockers missing');
ok(server.includes("process.env.RENTINORBIT_STAGING")&&server.includes("DB_BACKUP_ENABLED"),'staging exemption / backup flag missing');
ok(server.includes('last-verified-backup.json')&&server.includes('DB_BACKUP_MAX_AGE_HOURS'),'verified backup freshness evidence missing');
ok(backup.includes('process.env.RENTINORBIT_DB_PATH')&&backup.includes('process.env.DB_PATH'),'backup does not prioritize RENTINORBIT_DB_PATH');
ok(backup.includes('await db.backup(output)'),'SQLite online backup API missing');
ok(verify.includes("pragma('integrity_check'")&&verify.includes('last-verified-backup.json'),'backup integrity verification/evidence missing');
ok(auto.includes('await source.backup(output)')&&auto.includes("integrity_check"),'automated backup+verify command missing');
ok(pkg.scripts['backup:auto']==='node ops/backup-and-verify.js','backup:auto script missing');
console.log('PASS V172 DB backup launch blocker and verified backup workflow');
