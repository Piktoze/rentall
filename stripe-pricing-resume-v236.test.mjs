import assert from 'node:assert/strict';
import fs from 'node:fs';
const server=fs.readFileSync('./server.js','utf8');
const start=server.indexOf("app.post('/api/payments/create-intent'");
const end=server.indexOf("app.post('/api/payments/demo/confirm'",start);
assert.ok(start>=0&&end>start,'Real Stripe payment route must exist');
const route=server.slice(start,end);
const snapshotLoad=route.indexOf('getBookingPricingSnapshot(db,booking.bookingId)');
const pricingChoice=route.indexOf('const pricing=storedPricing||currentPricing');
const amountGuard=route.indexOf('Number(storedPricing.bookingAmountCents)!==amount');
const stripeFeeGuard=route.indexOf('Number(intent.application_fee_amount)!==platformFee');
const write=route.indexOf('saveBookingPricingSnapshot(db,{bookingId:booking.bookingId,pricing})',route.indexOf('if(booking.stripePaymentIntentId){'));
assert.ok(server.includes('getBookingPricingSnapshot,'),'Snapshot lookup must be imported');
assert.ok(snapshotLoad>=0&&pricingChoice>snapshotLoad,'Retries must select immutable booking pricing');
assert.ok(amountGuard>pricingChoice&&amountGuard<stripeFeeGuard,'Reject inconsistent stored amount before Stripe reuse');
assert.ok(route.includes('Number(storedPricing.supplierAmountCents)!==amount-Number(storedPricing.commissionAmountCents)'),'Stored fee and supplier net must reconcile');
assert.ok(route.includes("code:'BOOKING_PRICING_MISMATCH'"),'Corrupt snapshots must fail closed');
assert.ok(stripeFeeGuard>amountGuard&&write>stripeFeeGuard,'Stripe intent must be checked before any pricing rewrite');
assert.ok(route.includes('idempotencyKey:`booking:${booking.bookingId}:rental-payment`'),'Booking Stripe idempotency preserved');
console.log('PASS original booking commission survives supplier plan changes on Stripe retry');
