import fs from 'node:fs';
const ok=(v,m)=>{if(!v)throw new Error(m)};
const server=fs.readFileSync('./server.js','utf8');
const db=fs.readFileSync('./db.js','utf8');
const app=fs.readFileSync('./app.js','utf8');
const html=fs.readFileSync('./index.html','utf8');
const module=fs.readFileSync('./modules/marketplace-trust-v172.js','utf8');
const pkg=JSON.parse(fs.readFileSync('./package.json','utf8'));

ok(/REQUIRED_SCHEMA_VERSION=(?:17[2-9]|1[89]\d|[2-9]\d{2,})/.test(db),'schema version 172+ missing');
for(const table of ['rental_agreements','rental_conversations','rental_messages','renter_reviews'])ok(db.includes(`CREATE TABLE IF NOT EXISTS ${table}`),`${table} table missing`);
for(const fn of ['createRentalAgreement','acceptRentalAgreement','createOrGetRentalConversation','addRentalMessage','createRenterReview','getRenterReputation','getSupplierReputation'])ok(db.includes(`function ${fn}`)||db.includes(`function ${fn}(`),`${fn} missing`);
ok(server.includes("termsAccepted!==true")&&server.includes("code:'TERMS_REQUIRED'"),'server terms acceptance gate missing');
ok(server.includes("/api/rentals/bookings/:bookingId/agreement"),'agreement API missing');
ok(server.includes("/api/conversations/:conversationId/messages"),'message API missing');
ok(server.includes('containsOffPlatformContact'),'pre-booking contact protection missing');
ok(server.includes("replace(/\\b\\d{4}-\\d{2}-\\d{2}\\b/g,''"),'message contact filter must ignore ISO dates');
ok(server.includes("/api/supplier/bookings/:bookingId/customer-review"),'renter review API missing');
ok(server.includes("code:'CUSTOMER_IDENTITY_REQUIRED'"),'renter review customer identity guard missing');
ok(server.includes("/api/listings/:listingId/reputation"),'supplier reputation API missing');
ok(server.includes("/listing/:listingId/:slug?"),'SEO listing route missing');
ok(server.includes('const LISTING_SEO_COPY=')&&server.includes('seoCopy.dailyPrice')&&server.includes('seoCopy.cta'),'localized SEO listing labels missing');
ok(server.includes("const fixed=['/','/help','/terms','/privacy','/cookies','/fees']"),'sitemap legal pages missing');
for(const route of ['/help','/terms','/privacy','/cookies','/fees'])ok(server.includes(`'${route}'`),`${route} page missing`);
ok(app.includes("termsAccepted:document.getElementById('termsCheck')?.checked===true"),'checkout does not send terms acceptance');
ok(app.includes("const listingId=String(qs.get('listing')||'').trim()"),'listing deep-link handling missing');
ok(html.includes('id="regRole"')&&html.includes('value="customer"')&&html.includes('value="supplier"'),'customer/supplier registration choice missing');
ok(html.includes('id="messagesModal"')&&html.includes('id="agreementModal"')&&html.includes('id="renterReviewModal"'),'trust modals missing');
ok(html.includes('modules/marketplace-trust-v172.js'),'trust UI module not loaded');
ok(module.includes('Message supplier')&&module.includes('Supplier reputation')&&module.includes('Rate renter'),'trust UI actions missing');
ok(pkg.scripts['test:marketplace-trust-v172']==='node marketplace-trust-v172.test.js','test script missing');
console.log('PASS V172 marketplace trust foundation: agreements, messages, two-sided reputation, SEO and legal/help surfaces');
